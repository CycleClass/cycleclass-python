# Anote no papel o tipo de cada valor ANTES de rodar.
# Depois rode e confira quantos você acertou.

print("10", type("10"))
print(10, type(10))
print(10.0, type(10.0))
print(True, type(True))
print("True", type("True"))
print(3 / 2, type(3 / 2))

# Respostas: str, int, float, bool, str, float.
# A pegadinha: 3 / 2 dá 1.5, e a divisão com / sempre dá float,
